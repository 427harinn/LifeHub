test("occurrence scopes, projection parity, and ownership", async ({ page, browser }) => {
  const registration = await page.request.post("/api/auth/register", { data: { displayName: "M5 API", email: uniqueEmail(), password } });
  expect(registration.status()).toBe(201);
  const start = today();
  const input = { category: "home", title: "定例", place: null, memo: null, timingType: "scheduled", allDay: false, startDate: start, startTime: "08:00", endDate: start, endTime: "08:30", recurrence: { frequency: "daily", interval: 1, weekdays: null, dayOfMonth: null, startsOn: start, endsOn: shiftDate(start, 4) } };
  const createdResponse = await page.request.post("/api/events", { data: input });
  expect(createdResponse.status()).toBe(201);
  const created = await createdResponse.json() as { event: { id: string } };
  const eventId = created.event.id;
  const calendar = await page.request.get(`/api/calendar?month=${start.slice(0, 7)}`);
  const daily = await page.request.get(`/api/daily?date=${start}`);
  expect(calendar.status()).toBe(200);
  expect(daily.status()).toBe(200);
  const calendarPayload = await calendar.json() as { events: Array<{ id: string; occurrenceKey?: string }> };
  const dailyPayload = await daily.json() as { events: Array<{ id: string; occurrenceKey?: string }> };
  const occurrence = dailyPayload.events.find((event) => event.id === eventId);
  expect(occurrence?.occurrenceKey).toBeTruthy();
  expect(calendarPayload.events.some((event) => event.occurrenceKey === occurrence?.occurrenceKey)).toBe(true);

  const modified = await page.request.patch(`/api/events/${eventId}`, { data: { ...input, title: "今回だけ変更", scope: "occurrence", occurrenceKey: occurrence?.occurrenceKey } });
  expect(modified.status()).toBe(200);
  const changedDaily = await (await page.request.get(`/api/daily?date=${start}`)).json() as { events: Array<{ title: string; occurrenceKey?: string }> };
  expect(changedDaily.events.find((event) => event.occurrenceKey === occurrence?.occurrenceKey)?.title).toBe("今回だけ変更");
  await page.goto("/daily");
  await expect(page.getByText("今回だけ変更", { exact: true }).first()).toBeVisible();
  await page.screenshot({ path: path.join(evidenceDir, "occurrence-modified-390x844.png") });
  expect((await page.request.delete(`/api/events/${eventId}?scope=occurrence&occurrenceKey=${encodeURIComponent(occurrence?.occurrenceKey ?? "")}`)).status()).toBe(200);
  const cancelledDaily = await (await page.request.get(`/api/daily?date=${start}`)).json() as { events: Array<{ occurrenceKey?: string }> };
  expect(cancelledDaily.events.some((event) => event.occurrenceKey === occurrence?.occurrenceKey)).toBe(false);
  await page.reload();
  await expect(page.getByText("今回だけ変更", { exact: true })).toHaveCount(0);
  await page.screenshot({ path: path.join(evidenceDir, "occurrence-cancelled-390x844.png") });

  const followingResponse = await page.request.patch(`/api/events/${eventId}`, { data: { ...input, title: "次回以降変更", scope: "following", occurrenceKey: `event:${eventId}:${shiftDate(start, 1)}T08:00` } });
  expect(followingResponse.status()).toBe(200);
  const seriesCreatedResponse = await page.request.post("/api/events", { data: { ...input, title: "系列編集前" } });
  const seriesCreated = await seriesCreatedResponse.json() as { event: { id: string } };
  expect((await page.request.patch(`/api/events/${seriesCreated.event.id}`, { data: { ...input, title: "系列編集後", scope: "series" } })).status()).toBe(200);
  const seriesDaily = await (await page.request.get(`/api/daily?date=${start}`)).json() as { events: Array<{ id: string; title: string }> };
  expect(seriesDaily.events.find((event) => event.id === seriesCreated.event.id)?.title).toBe("系列編集後");
  expect((await page.request.delete(`/api/events/${seriesCreated.event.id}?scope=series`)).status()).toBe(200);
  expect((await page.request.get(`/api/daily?date=${start}`)).status()).toBe(200);
  const followingDeleteCreatedResponse = await page.request.post("/api/events", { data: { ...input, title: "これ以降削除" } });
  const followingDeleteCreated = await followingDeleteCreatedResponse.json() as { event: { id: string } };
  expect((await page.request.delete(`/api/events/${followingDeleteCreated.event.id}?scope=following&occurrenceKey=event:${followingDeleteCreated.event.id}:${shiftDate(start, 1)}T08:00`)).status()).toBe(200);
  const followingDeleteDaily = await (await page.request.get(`/api/daily?date=${shiftDate(start, 1)}`)).json() as { events: Array<{ id: string }> };
  expect(followingDeleteDaily.events.some((event) => event.id === followingDeleteCreated.event.id)).toBe(false);
  const otherContext = await browser.newContext();
  const otherPage = await otherContext.newPage();
  expect((await otherPage.request.post("/api/auth/register", { data: { displayName: "Other", email: uniqueEmail(), password } })).status()).toBe(201);
  expect((await otherPage.request.get(`/api/events/${eventId}`)).status()).toBe(404);
  expect((await otherPage.request.patch(`/api/events/${eventId}`, { data: input })).status()).toBe(404);
  expect((await otherPage.request.delete(`/api/events/${eventId}`)).status()).toBe(404);
  await otherContext.close();
  await mkdir(evidenceDir, { recursive: true });
  await page.goto("/");
  await page.reload();
  await page.getByRole("button", { name: "デイリー" }).click();
  await page.getByRole("button", { name: "次の日" }).click();
  await expect(page.getByText("次回以降変更", { exact: true }).first()).toBeVisible();
  await page.screenshot({ path: path.join(evidenceDir, "following-series-390x844.png") });
  const row = page.locator(".tap-expand-row").filter({ hasText: "次回以降変更" }).first();
  await row.locator(".tap-expand-row__trigger").click();
  await row.locator(".event-inline-detail").getByRole("button", { name: "編集", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "編集する範囲" })).toBeVisible();
  await expect(page.getByRole("button", { name: "この予定のみ" })).toBeVisible();
  await expect(page.getByRole("button", { name: "この予定以降" })).toBeVisible();
  await expect(page.getByRole("button", { name: "すべての予定" })).toBeVisible();
  await page.waitForTimeout(250);
  await page.screenshot({ path: path.join(evidenceDir, "scope-selection-390x844.png") });
  await page.getByRole("dialog").getByRole("button", { name: "この予定のみ" }).click();
  await expect(page.getByRole("heading", { name: "予定を編集" })).toBeVisible();
  await page.screenshot({ path: path.join(evidenceDir, "occurrence-edit-form-390x844.png") });
  await page.getByRole("button", { name: "削除", exact: true }).click();
  const deleteScope = page.getByRole("dialog", { name: "削除する範囲" });
  await expect(deleteScope).toBeVisible();
  await expect(deleteScope.getByRole("button", { name: "この予定のみ", exact: true })).toBeVisible();
  await expect(deleteScope.getByRole("button", { name: "この予定以降", exact: true })).toBeVisible();
  await expect(deleteScope.getByRole("button", { name: "すべての予定", exact: true })).toBeVisible();
  await deleteScope.getByRole("button", { name: "この予定のみ", exact: true }).click();
  const deleteConfirmation = page.getByRole("dialog", { name: "予定を削除" });
  await expect(deleteConfirmation).toBeVisible();
  await deleteConfirmation.getByRole("button", { name: "キャンセル", exact: true }).click();
  await expect(deleteConfirmation).toHaveCount(0);
});
